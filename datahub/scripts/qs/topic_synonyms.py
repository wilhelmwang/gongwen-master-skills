# 预编译：口语 key 中含用户 query 片段即触发
_RULES = [(k, v) for k, v in TOPIC_SYNONYMS.items()]


def expand_query(q: str, max_terms: int = 6):
    """口语 query → 扩展检索词列表（原词优先 + 概念词补充）。

    返回 [原词, 概念词1, 概念词2, ...]（去重，最多 max_terms）。
    """
    out = [q]
    ql = q.lower()
    for key, synonyms in _RULES:
        if key in q or key in ql:
            for s in synonyms:
                if s not in out:
                    out.append(s)
    return out[:max_terms]
